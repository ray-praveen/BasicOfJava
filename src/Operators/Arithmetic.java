
static void main(){

    // Arithmetic Operator
    int solveThisWeek = 25;
    int solvedLastWeek = 15;

    int total = solvedLastWeek + solveThisWeek;
    int difference = solveThisWeek - solvedLastWeek;
    int projected = solveThisWeek * 4;
    int average = solveThisWeek / 7;
    int remainder = solveThisWeek % 7;

    System.out.println(total);
    System.out.println(difference);
    System.out.println(projected);
    System.out.println(average);
    System.out.println(remainder);

}